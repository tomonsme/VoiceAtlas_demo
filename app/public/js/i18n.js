/* 画面表示の言語切り替え。
 *
 * 辞書は「日本語を正、英語を対訳」として持つ。UIの文言（chrome）だけを対象にし、
 * 研究名や本文などの内容（content）はデータ側が言語別に持つ。内容を辞書に混ぜると、
 * 研究が増えるたびに辞書を触ることになるため。
 */

const STORE_KEY = "voiceatlas-lang";

export const languages = [
  { code: "ja", label: "日本語" },
  { code: "en", label: "English" }
];

function detect() {
  try {
    const saved = localStorage.getItem(STORE_KEY);
    if (saved && languages.some((l) => l.code === saved)) return saved;
  } catch (_error) {
    /* localStorage が使えない場合は既定値へ */
  }
  return String(navigator.language || "").toLowerCase().startsWith("en") ? "en" : "ja";
}

let current = detect();

export function getLang() {
  return current;
}

export function setLang(code) {
  if (!languages.some((l) => l.code === code)) return;
  current = code;
  try {
    localStorage.setItem(STORE_KEY, code);
  } catch (_error) {
    /* 保存できなくても表示は切り替わる */
  }
  applyDocumentLanguage();
}

/** <html lang> と meta description を現在の言語に合わせる。 */
export function applyDocumentLanguage() {
  document.documentElement.lang = current;
  const description = document.querySelector('meta[name="description"]');
  if (description) description.setAttribute("content", t("meta.description"));
  // インストール時の説明文もマニフェスト側にあるので、言語ごとに差し替える。
  const manifest = document.querySelector('link[rel="manifest"]');
  if (manifest) manifest.setAttribute("href", current === "ja" ? "/manifest.webmanifest" : "/manifest.en.webmanifest");
}

/** データ側が {ja, en} の形で持つ内容を、現在の言語で取り出す。 */
export function pick(value) {
  if (value && typeof value === "object" && !Array.isArray(value)) {
    return value[current] ?? value.ja ?? "";
  }
  return value ?? "";
}

/** t("auth.login") / t("today.streakDays", { n: 5 }) */
export function t(key, vars) {
  const table = dictionary[current] || dictionary.ja;
  let text = table[key];
  if (text === undefined) text = dictionary.ja[key];
  if (text === undefined) return key;
  if (typeof text === "function") return text(vars || {});
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (_m, name) => (vars[name] ?? ""));
}

